    /** What the registry says about a code, or null for a code outside it (http-<status>, the website API's codes). */
    public static function info(string $code): ?ErrorInfo
    {
        $row = self::DETAILS[$code] ?? null;
        if ($row === null) {
            return null;
        }
        return new ErrorInfo($code, $row[0], $row[1], $row[2], $row[3], $row[4]);
    }

    /** Whether the registry has the code. */
    public static function isKnown(string $code): bool
    {
        return isset(self::DETAILS[$code]);
    }
